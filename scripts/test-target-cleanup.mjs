import { readFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';
import assert from 'node:assert/strict';
const source=readFileSync('ui/engine/2.js','utf8');
const cleaners=source.slice(source.indexOf('const FILLW ='), source.indexOf('async function cleanAnim('));
const go=source.slice(source.indexOf('async function polishAndGo('), source.indexOf('function retry()'));
