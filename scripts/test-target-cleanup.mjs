runInNewContext(cleaners+'\n'+go,ctx);
const setWords=t=>ctx.words=t.split(/\s+/).map(t=>({t,dead:false}));
let received='';
ctx.ENV.polish=async t=>{received=t;return 'Смотри, я нажал зелёную кнопку.'};
