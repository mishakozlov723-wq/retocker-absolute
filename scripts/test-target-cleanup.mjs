setWords('ну смотри, я нажал зелёную кнопку.');ctx.S.smart=true;
ctx.ENV.polish=async()=>{throw new Error('network')}; await ctx.polishAndGo(1,true);
assert.equal(ctx.output,'Смотри, я нажал зелёную кнопку.');
setWords('ну смотри, я нажал зелёную кнопку.');ctx.ENV.polish=async()=>null;await ctx.polishAndGo(1,true);
assert.equal(ctx.output,'Смотри, я нажал зелёную кнопку.');
